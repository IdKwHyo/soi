import assert from 'node:assert/strict';
import {sampleMenus,analyze,contribution,project,evaluate,parseCsv,menuCsv,createDrafts} from './dist/core.mjs';
assert.ok(Math.abs(contribution(sampleMenus[0])-37.2)<1e-10);
const a=analyze(sampleMenus);
assert.equal(a.orders,497);
assert.equal(a.recommended,'Basil chicken rice');
assert.deepEqual(parseCsv(menuCsv(sampleMenus)),sampleMenus);
assert.deepEqual(parseCsv('\uFEFF'+menuCsv([{...sampleMenus[0],name:'Rice, "special"'}])),[{...sampleMenus[0],name:'Rice, "special"'}]);
assert.throws(()=>parseCsv('menu,weekday_orders,weekend_orders,price,ingredient_cost,packaging_cost,fee_percent\nRice,,1,80,25,5,20'));
assert.throws(()=>parseCsv(menuCsv([{...sampleMenus[0],fee:101}])));
assert.throws(()=>parseCsv(menuCsv([{...sampleMenus[0],weekday:1.5}])));
assert.throws(()=>analyze([{...sampleMenus[0],price:Infinity}]));
const plan={discount:10,extraOrders:40,existingOrders:20,budget:600};
const p=project(sampleMenus[0],plan);
assert.ok(Math.abs(p.offer-30.08)<1e-10);
assert.ok(Math.abs(p.existingLoss-142.4)<1e-10);
assert.ok(Math.abs(p.net-460.8)<1e-10);
assert.equal(p.breakEven,25);
assert.ok(Math.abs(evaluate(sampleMenus[0],plan,{totalOrders:60,baselineOrders:20,spend:600}).net-p.net)<1e-10);
assert.ok(evaluate(sampleMenus[0],plan,{totalOrders:10,baselineOrders:20,spend:600}).net<0);
assert.throws(()=>project(sampleMenus[0],{...plan,discount:NaN}));
assert.throws(()=>project(sampleMenus[0],{...plan,extraOrders:1.5}));
assert.equal(project({...sampleMenus[0],ingredients:100},plan).breakEven,null);
assert.equal(analyze([{...sampleMenus[0],ingredients:100}]).recommended,null);
const drafts=createDrafts({name:'Test Restaurant',tone:'Direct',audience:'Local workers'},sampleMenus[0],plan);
assert.ok(drafts.social.includes('THB 80.10'));
assert.ok(drafts.social.includes('Test Restaurant'));
console.log('PASS: contribution, ranking, CSV import, quoted values, input validation, campaign economics, break-even, loss scenarios, results and drafts.');

